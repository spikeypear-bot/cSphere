import { expect, test } from '@playwright/test'
import { apiGet, apiToken, createVenue, createCompetingBooking, leadAssigns, requestIdOf, signedIn, submitRequest, uniqueName } from './support.ts'

test('Venue Staff hold, release and convert a coordinator booking without duplicating the reservation', async ({ browser, request }, testInfo) => {
  test.setTimeout(180_000)
  const name = uniqueName('Hold journey')
  const venueName = uniqueName('Hold venue')
  const venueId = await createVenue(request, venueName)
  const day = new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 10)
  const organiser = await signedIn(browser, 'eo1')
  await submitRequest(organiser, name, `${day}T10:00`, `${day}T12:00`)
  const requestId = await requestIdOf(request, name)
  const lead = await signedIn(browser, 'ecl1')
  await leadAssigns(lead, requestId)
  const coordinator = await signedIn(browser, 'ec1')
  await coordinator.goto(`/coordinator/requests/${requestId}`)
  await coordinator.getByRole('group', { name: 'Choose an outcome' }).getByRole('button', { name: 'Approve' }).click()
  await coordinator.getByRole('button', { name: 'Approve and start planning' }).click()
  await expect(coordinator).toHaveURL(/\/coordinator\/events\/[0-9a-f-]{36}/)
  const eventId = coordinator.url().split('/events/')[1].split(/[/?#]/)[0]
  await coordinator.goto(`/coordinator/events/${eventId}/venue-booking`)
  await coordinator.getByPlaceholder('Search by address or details').fill(venueName)
  await coordinator.getByRole('button', { name: new RegExp(venueName) }).first().click()
  await coordinator.getByRole('button', { name: `Request ${venueName}` }).click()
  await expect(coordinator.getByText(`Booking request for ${venueName} sent to Venue Staff`)).toBeVisible()
  const token = await apiToken(request, 'ec1')
  const requested = await apiGet<{ bookingId: string; startDatetime: string; endDatetime: string }[]>(request, token, `/api/events/${eventId}/venue-bookings`)
  const competingId = await createCompetingBooking(request, venueId, uniqueName('Competing workshop'), requested[0].startDatetime, requested[0].endDatetime)
  const staff = await signedIn(browser, 'vs1')
  await staff.goto(`/venue-staff/bookings/${requested[0].bookingId}`)
  const panel = staff.getByRole('region', { name: 'Tentative venue hold' })
  // datetime-local is explicitly SGT, independent of the browser's timezone.
  const expiry = new Date(Date.now() + 8 * 3600000 + 86400000).toISOString().slice(0, 16)
  await staff.getByRole('button', { name: 'Put on Tentative Hold', exact: true }).click()
  await panel.getByLabel('Hold expiry (Singapore time)').fill(expiry)
  await staff.screenshot({ path: testInfo.outputPath('hold-form.png'), fullPage: true })
  await panel.getByRole('button', { name: 'Place tentative hold' }).click()
  await expect(panel.getByText('Tentative hold created.')).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Release Hold' })).toBeVisible()
  await expect(staff.getByRole('button', { name: 'Approve Booking', exact: true })).toBeDisabled()
  const holdColour = await staff.getByLabel('Status: tentative').evaluate(node => getComputedStyle(node).color)
  await staff.screenshot({ path: testInfo.outputPath('active-hold.png'), fullPage: true })
  await staff.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => staff.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await staff.screenshot({ path: testInfo.outputPath('active-hold-mobile.png'), fullPage: true })
  await staff.setViewportSize({ width: 1280, height: 720 })
  const approvals = await staff.context().newPage()
  await approvals.goto('/venue-staff/booking-approvals')
  const heldQueue = approvals.getByRole('region', { name: 'Tentative venue holds' })
  await expect(heldQueue.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(heldQueue.locator('[data-booking-status="tentative"]').first()).toHaveCSS('color', holdColour)
  await approvals.getByRole('group', { name: 'Filter booking approvals by status' }).getByRole('button', { name: /^Tentative Hold \d+$/ }).click()
  await expect(approvals.getByRole('region', { name: 'Pending booking requests' })).toHaveCount(0)
  await approvals.screenshot({ path: testInfo.outputPath('hold-queue.png'), fullPage: true })
  const competitor = await staff.context().newPage()
  await competitor.goto(`/venue-staff/bookings/${competingId}`)
  await competitor.getByRole('button', { name: 'Put on Tentative Hold', exact: true }).click()
  await competitor.getByLabel('Hold expiry (Singapore time)').fill(expiry)
  await competitor.getByRole('button', { name: 'Place tentative hold' }).click()
  await expect(competitor.getByRole('alert')).toContainText('occupied period conflicts')
  await expect(competitor.getByRole('alert').locator('.booking-conflict-card .booking-time-conflict').first()).toBeVisible()
  await competitor.screenshot({ path: testInfo.outputPath('hold-conflict.png'), fullPage: true })
  const schedule = await staff.context().newPage()
  await schedule.goto('/venue-staff/availability-calendar')
  await schedule.getByLabel('Venue', { exact: true }).selectOption(venueId)
  const currentMonth = new Date(Date.now() + 8 * 3600000).toISOString().slice(0, 7)
  if (day.slice(0, 7) !== currentMonth) await schedule.getByRole('button', { name: 'Next month' }).click()
  await expect(schedule.getByRole('button', { name: new RegExp(`Tentative Hold.*${name}`) }).first()).toBeVisible()
  await expect(schedule.locator('button[data-booking-status="tentative"]').first()).toHaveCSS('color', holdColour)
  await panel.getByRole('button', { name: 'Release Hold' }).click()
  await expect(panel.getByText('Hold released.')).toBeVisible()
  await expect(panel.getByText('Released', { exact: true })).toBeVisible()
  await schedule.getByRole('button', { name: 'Refresh schedule' }).click()
  await expect(schedule.getByRole('button', { name: new RegExp(`Pending request.*${name}`) }).first()).toBeVisible()
  await expect(schedule.getByRole('button', { name: new RegExp(`Tentative Hold.*${name}`) })).toHaveCount(0)
  await staff.getByRole('button', { name: 'Put on Tentative Hold', exact: true }).click()
  await panel.getByLabel('Hold expiry (Singapore time)').fill(expiry)
  await panel.getByRole('button', { name: 'Place tentative hold' }).click()
  await expect(panel.getByRole('button', { name: 'Convert Hold to Approved Booking' })).toBeVisible()
  await panel.getByRole('button', { name: 'Convert Hold to Approved Booking' }).click()
  await expect(staff.getByLabel('Status: approved')).toBeVisible()
  await expect(panel.getByText('Converted', { exact: true })).toBeVisible()
  await schedule.getByRole('button', { name: 'Refresh schedule' }).click()
  await expect(schedule.getByRole('button', { name: new RegExp(`Approved booking.*${name}`) }).first()).toBeVisible()
  await expect(schedule.getByRole('button', { name: new RegExp(`Tentative Hold.*${name}`) })).toHaveCount(0)
  const after = await apiGet<{ status: string; holds: { status: string }[] }[]>(request, token, `/api/events/${eventId}/venue-bookings`)
  expect(after).toHaveLength(1)
  expect(after[0].status).toBe('approved')
  expect(after[0].holds.map(h => h.status).sort()).toEqual(['converted', 'released'])
  await coordinator.goto(`/coordinator/events/${eventId}`)
  await expect(coordinator.getByText('Planning').first()).toBeVisible()
  await expect(coordinator.getByRole('region', { name: 'Change log' })).toContainText('converted a tentative hold')
  for (const page of [organiser, lead, coordinator, staff]) await page.context().close()
})
