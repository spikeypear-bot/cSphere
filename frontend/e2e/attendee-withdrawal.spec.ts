// @stories AT08 AT01 AT02 AT03 AT04
import { expect, test } from '@playwright/test'
import { apiGet, apiToken, confirmedEventByApi, createVenue, signedIn, uniqueName } from './support.ts'

test('AT08 AT01 AT02 AT03 AT04 (happy): cancel a withdrawal, confirm it, reopen its receipt and preserve history after re-registering', async ({ browser, request }, testInfo) => {
  test.setTimeout(120_000)
  const eventName = uniqueName('AT08 withdrawal')
  const venue = await createVenue(request, uniqueName('AT08 venue'))
  const start = new Date(Date.now() + 35 * 24 * 60 * 60 * 1000)
  start.setUTCHours(1, 0, 0, 0)
  const eventId = await confirmedEventByApi(request, eventName, venue, start.toISOString(),
    new Date(start.getTime() + 3 * 60 * 60 * 1000).toISOString(), {
      registrationCapacity: 2, registrationOpensAt: new Date(Date.now() - 24 * 60 * 60 * 1000).toISOString(),
    })
  const attendee = await signedIn(browser, 'att1')
  const token = await apiToken(request, 'att1')
  try {
    await attendee.goto(`/attendee/events/${eventId}`)
    await attendee.getByRole('button', { name: 'Register for this event' }).click()
    await expect(attendee.getByText('Registration Confirmed', { exact: true })).toBeVisible()
    await attendee.getByRole('link', { name: 'View registration confirmation' }).click()
    const detailUrl = attendee.url()
    const id = detailUrl.split('/').pop()!
    const initial = await apiGet<{ reference: string; registeredAt: string }>(request, token, `/api/attendee/registrations/${id}`)
    const withdrawals: string[] = []
    attendee.on('request', req => { if (req.method() === 'POST' && req.url().endsWith('/withdraw')) withdrawals.push(req.url()) })
    await attendee.getByRole('button', { name: 'Withdraw Registration' }).click()
    const dialog = attendee.getByRole('dialog', { name: 'Withdraw your registration?' })
    await expect(dialog.getByText(eventName, { exact: true })).toBeVisible()
    await expect(dialog.getByText(initial.reference, { exact: true })).toBeVisible()
    await expect(dialog.getByRole('button', { name: 'Keep registration' })).toBeFocused()
    await dialog.getByRole('button', { name: 'Keep registration' }).click()
    await expect(dialog).not.toBeVisible()
    await attendee.getByRole('button', { name: 'Withdraw Registration' }).click()
    await attendee.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    expect(withdrawals).toHaveLength(0)
    const untouched = await apiGet<{ registrationStatus: string; withdrawnAt: string | null }>(request, token, `/api/attendee/registrations/${id}`)
    expect(untouched.registrationStatus).toBe('confirmed')
    expect(untouched.withdrawnAt).toBeNull()
    await attendee.setViewportSize({ width: 390, height: 844 })
    await attendee.getByRole('button', { name: 'Withdraw Registration' }).click()
    await expect(dialog).toBeVisible()
    await attendee.screenshot({ path: testInfo.outputPath('withdrawal-confirm-mobile.png'), fullPage: true })
    await dialog.getByRole('button', { name: 'Confirm withdrawal' }).click()
    await expect(attendee.getByText('Withdrawn', { exact: true })).toBeVisible()
    await expect(attendee.getByText('Withdrawal date', { exact: true })).toBeVisible()
    await expect(attendee.getByText(initial.reference, { exact: true })).toBeVisible()
    await expect(attendee.getByRole('button', { name: 'Withdraw Registration' })).toHaveCount(0)
    expect(withdrawals).toHaveLength(1)
    const saved = await apiGet<{ registrationStatus: string; withdrawnAt: string; registeredAt: string; reference: string }>(request, token, `/api/attendee/registrations/${id}`)
    expect(saved).toMatchObject({ registrationStatus: 'withdrawn', reference: initial.reference, registeredAt: initial.registeredAt })
    expect(saved.withdrawnAt).toBeTruthy()
    await attendee.getByRole('button', { name: /Notifications/ }).click()
    const receipt = attendee.getByRole('menu').getByRole('button').filter({ hasText: `Your registration for "${eventName}" has been withdrawn` })
    await expect(receipt).toBeVisible()
    await receipt.click()
    await expect(attendee).toHaveURL(detailUrl)
    await attendee.reload()
    await expect(attendee.getByText('Withdrawn', { exact: true })).toBeVisible()
    await attendee.screenshot({ path: testInfo.outputPath('withdrawal-saved-mobile.png'), fullPage: true })
    await attendee.getByRole('link', { name: 'My Registrations', exact: true }).last().click()
    const history = attendee.getByRole('listitem').filter({ hasText: initial.reference })
    await expect(history.getByText('Withdrawn', { exact: true })).toBeVisible()
    await history.getByRole('link', { name: eventName }).click()
    await attendee.getByRole('link', { name: 'View latest event details' }).click()
    await expect(attendee.getByText('2 places available', { exact: true })).toBeVisible()
    await attendee.getByRole('button', { name: 'Register for this event' }).click()
    await expect(attendee.getByText('Registration Confirmed', { exact: true })).toBeVisible()
    await attendee.goto(detailUrl)
    await expect(attendee.getByText(initial.reference, { exact: true })).toBeVisible()
    await expect(attendee.getByText('Withdrawn', { exact: true })).toBeVisible()
    const notices = await apiGet<{ type: string; linkPath: string; eventId: string }[]>(request, token, '/api/notifications')
    expect(notices.filter(n => n.type === 'attendee_registration_withdrawn' && n.eventId === eventId))
      .toEqual([expect.objectContaining({ linkPath: `/attendee/my-registrations/${id}` })])
    const other = await signedIn(browser, 'att2')
    try {
      await other.goto(`/attendee/my-registrations/${id}`)
      await expect(other.getByRole('alert')).toContainText('unavailable or does not belong')
      await expect(other.getByRole('button', { name: 'Withdraw Registration' })).toHaveCount(0)
      await expect(other.getByText(initial.reference, { exact: true })).toHaveCount(0)
    } finally { await other.context().close() }
  } finally { await attendee.context().close() }
})
